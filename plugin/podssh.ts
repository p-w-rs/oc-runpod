import { join } from "node:path"
import { RunDir, type ShellCaller, type Supply } from "oc-secure-kit"
import { podAlias, SSH_KEY, type Account } from "./model.js"
import { publicKeyOf, type PodRecord, type RunpodService } from "./service.js"

/** Shell commands reference this to reach pods: ssh -F "$RUNPOD_SSH_CONFIG" <alias>. */
export const SSH_CONFIG_VAR = "RUNPOD_SSH_CONFIG"
const REFERENCE = new RegExp(`\\$\\{?${SSH_CONFIG_VAR}\\b`)
const ALIAS = /\brp-[a-z0-9][a-z0-9-]*[a-z0-9]\b/g
const PODS_TTL = 15_000

export type SshState = "ready" | "stopped" | "no-port" | "no-ip" | "no-key" | "unknown"

export interface PodSsh {
  readonly account: string
  readonly alias: string
  readonly pod: PodRecord
  readonly state: SshState
  readonly host?: string
  readonly port?: number
  readonly user?: string
}

/** Key body ("ssh-ed25519 AAAA…") without the comment. */
export const keyBody = (line: string) => line.trim().split(/\s+/).slice(0, 2).join(" ")

/** How ready a pod is for the plugin's SSH key, without revealing env values. */
export function sshState(pod: PodRecord & { env?: Record<string, string> | null; ports?: string[] | null }, publicKey: string | undefined): SshState {
  if (pod.status !== "RUNNING") return "stopped"
  if (!pod.ssh?.direct) {
    if (!(pod.ports ?? []).includes("22/tcp")) return "no-port"
    // RunPod assigns the public address within a minute or two of starting; after that it is not coming.
    return pod.startedAt && Date.now() - Date.parse(pod.startedAt) > 5 * 60_000 ? "no-ip" : "unknown"
  }
  if (!publicKey || !pod.env) return "unknown"
  const keys = pod.env.PUBLIC_KEY
  return typeof keys === "string" && keys.includes(keyBody(publicKey).split(" ")[1]!) ? "ready" : "no-key"
}

export function renderPodConfig(entries: readonly PodSsh[], options: { keysDir: string; knownHosts: string }): string {
  const lines = ["# Generated by oc-runpod for one command. Use: ssh -F \"$RUNPOD_SSH_CONFIG\" <pod alias>", ""]
  for (const entry of entries) {
    if (!entry.host || !entry.port) continue
    lines.push(
      `Host ${entry.alias}`,
      `  HostName ${entry.host}`,
      `  Port ${entry.port}`,
      `  User ${entry.user ?? "root"}`,
      `  IdentityFile ${join(options.keysDir, entry.account)}`,
      "  IdentitiesOnly yes",
      "  IdentityAgent none",
      // RunPod reuses addresses across pods: pin host keys per pod, not per address.
      `  HostKeyAlias runpod-${entry.pod.id}`,
      `  UserKnownHostsFile ${options.knownHosts}`,
      "  StrictHostKeyChecking accept-new",
      "  BatchMode yes",
      "  ServerAliveInterval 30",
      "  ConnectTimeout 20",
      "",
    )
  }
  return lines.join("\n")
}

export const STATE_HELP: Record<Exclude<SshState, "ready">, string> = {
  stopped: "is not running; start it first (pod-action start)",
  "no-port": "does not expose port 22/tcp, so it has no direct SSH; runpod_ssh_setup pod=<id> adds it (restarts the pod)",
  "no-ip": "has no public SSH address (only RunPod's interactive relay, which cannot run commands or copy files); a pod created with ports [\"22/tcp\"] on Secure Cloud gets one",
  "no-key": "was created without the plugin's SSH key; runpod_ssh_setup pod=<id> adds it (restarts the pod)",
  unknown: "has no direct SSH address yet; wait a moment after it starts, then try again",
}

/** Pods across accounts, refreshed at most every few seconds. */
export class PodDirectory {
  #cache = new Map<string, { at: number; pods: PodRecord[] }>()
  constructor(private readonly service: RunpodService) {}

  invalidate(account?: string): void { if (account) this.#cache.delete(account); else this.#cache.clear() }

  async pods(account: Account, fresh = false): Promise<PodRecord[]> {
    const cached = this.#cache.get(account.id)
    if (cached && !fresh && Date.now() - cached.at < PODS_TTL) return cached.pods
    const pods = await this.service.pods(account)
    this.#cache.set(account.id, { at: Date.now(), pods })
    return pods
  }

  async describe(account: Account, pod: PodRecord): Promise<PodSsh> {
    const key = await this.service.vault.get(account.id, SSH_KEY)
    const state = sshState(pod as never, key ? publicKeyOf(key) : undefined)
    const direct = pod.ssh?.direct
    return { account: account.id, alias: podAlias(account.id, pod), pod, state, ...(direct && { host: direct.host, port: direct.port, user: direct.username ?? "root" }) }
  }

  /** Finds a pod by id, name or alias in one account. */
  async find(account: Account, ref: string): Promise<PodRecord> {
    const pods = await this.pods(account, true)
    const matches = pods.filter(pod => pod.id === ref || pod.name === ref || podAlias(account.id, pod) === ref)
    if (matches.length === 1) return matches[0]!
    if (matches.length > 1) throw new Error(`Several pods in ${account.id} match ${JSON.stringify(ref)}: ${matches.map(pod => pod.id).join(", ")}. Use the pod id.`)
    throw new Error(`No pod ${JSON.stringify(ref)} in ${account.id}. Pods: ${pods.slice(0, 20).map(pod => `${pod.name ?? pod.id} (${pod.id}, ${pod.status})`).join(", ") || "(none)"}`)
  }

  /** Supplies a per-command ssh config for the pods a shell command names. Undefined: the command is left alone. */
  async prepareCommand(command: string, caller: ShellCaller): Promise<Supply | undefined> {
    if (!REFERENCE.test(command)) return undefined
    const accounts = await this.service.store.list()
    const named = [...new Set(command.match(ALIAS) ?? [])]
    const notes: string[] = []
    const entries: PodSsh[] = []
    for (const account of accounts) {
      const prefix = podAlias(account.id, { id: "x", name: "x" }).slice(0, -1)
      const wanted = named.filter(alias => alias.startsWith(prefix))
      if (!wanted.length || !(await this.service.signedIn(account))) continue
      try {
        await this.service.bridge.check({
          sessionID: caller.sessionID, ...(caller.agent && { agent: caller.agent }), ...(caller.source && { source: caller.source }),
          capability: "ssh", entities: [account.id], metadata: { pods: wanted.join(", "), command: command.length > 400 ? `${command.slice(0, 400)}…` : command },
        })
      } catch (error) {
        notes.push(`SSH to ${account.id}'s pods was not allowed: ${(error as Error).message.slice(0, 200)}`)
        continue
      }
      const pods = await this.pods(account).catch(error => { notes.push(`Could not list ${account.id}'s pods: ${(error as Error).message.slice(0, 200)}`); return [] as PodRecord[] })
      for (const alias of wanted) {
        const pod = pods.find(item => podAlias(account.id, item) === alias)
        if (!pod) { notes.push(`${alias}: no such pod in ${account.id} (runpod_list shows the aliases).`); continue }
        const entry = await this.describe(account, pod)
        if (entry.state !== "ready" && entry.state !== "unknown") notes.push(`${alias} ${STATE_HELP[entry.state]}.`)
        if (entry.host) entries.push(entry)
        else if (entry.state === "unknown") notes.push(`${alias} ${STATE_HELP.unknown}.`)
      }
    }
    if (!named.length) notes.push(`No pod alias is named in this command; $${SSH_CONFIG_VAR} is empty. runpod_list shows the aliases (rp-<account>-<pod>).`)
    const runDir = await RunDir.create(join(this.service.dir, "run"))
    const keysDir = runDir.file("keys")
    let secrets = false
    for (const account of new Set(entries.map(entry => entry.account))) {
      const key = await this.service.vault.get(account, SSH_KEY)
      if (key) { await runDir.write(join("keys", account), key.endsWith("\n") ? key : `${key}\n`); secrets = true }
      else notes.push(`${account} has no plugin SSH key yet: runpod_ssh_setup account=${account}.`)
    }
    const config = renderPodConfig(entries, { keysDir, knownHosts: join(this.service.dir, "known_hosts") })
    return { env: { [SSH_CONFIG_VAR]: await runDir.write("ssh_config", config) }, notes, secrets, runDir }
  }
}

/** Tip after a failed command that used pod aliases without the plugin's config. */
export function sshTip(command: string, result: unknown): string | undefined {
  if (!/\brp-[a-z0-9-]+/.test(command) || REFERENCE.test(command)) return undefined
  const text = JSON.stringify(result ?? "")
  if (!/Could not resolve hostname|ssh: connect|Permission denied|rsync/.test(text)) return undefined
  return `Pod aliases only work with the plugin's config: ssh -F "$${SSH_CONFIG_VAR}" <alias>, or rsync -e "ssh -F '$${SSH_CONFIG_VAR}'" …`
}
